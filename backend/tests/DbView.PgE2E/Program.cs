var failures = 0;
void Check(bool ok, string name, string detail = "")
{
    Console.WriteLine((ok ? "  [PASS] " : "  [FAIL] ") + name + (string.IsNullOrEmpty(detail) ? "" : " -> " + detail));
    if (!ok) failures++;
}

// ===== 读取本地配置库里的 PG 凭据 =====
var configDb = @"D:\work\tools\DbView\backend\src\DbView.WebApi\bin\Debug\net10.0\DbView.db";
using var cfg = new SqliteConnection($"Data Source={configDb}");
await cfg.OpenAsync();
using var cfgCmd = cfg.CreateCommand();
cfgCmd.CommandText = "SELECT Host,Port,DatabaseName,Username,Password FROM dbview_connections WHERE DbType='postgresql' LIMIT 1";
using var cfgReader = await cfgCmd.ExecuteReaderAsync();
if (!await cfgReader.ReadAsync()) { Console.WriteLine("NO_PG_CONNECTION"); return 2; }
var host = cfgReader.GetString(0);
