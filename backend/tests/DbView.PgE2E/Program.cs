cfgReader.Close();

string Cs(string database) => $"Host={host};Port={port};Database={database};Username={user};Password={pwd};Pooling=false";

var suffix = DateTime.UtcNow.ToString("yyyyMMddHHmmss");
var srcDb = "dbview_e2e_src_" + suffix;
var dstDb = "dbview_e2e_dst_" + suffix;

// ===== 1. 创建两个临时数据库（不碰用户的 aichat 库）=====
await using (var admin = new NpgsqlConnection(Cs("postgres")))
{
    await admin.OpenAsync();
    foreach (var db in new[] { srcDb, dstDb })
    {
        await using var c = admin.CreateCommand();
        c.CommandText = $"CREATE DATABASE \"{db}\"";
        await c.ExecuteNonQueryAsync();
    }
}
Console.WriteLine($"TEMP_DB src={srcDb} dst={dstDb}");

Connection SrcConn() => new()
{
    Id = 880000 + DateTime.UtcNow.Millisecond, Name = srcDb, DbType = "postgresql",
    Host = host, Port = port, DatabaseName = srcDb, Username = user, Password = pwd
};
Connection DstConn() => new()
{
    Id = 890000 + DateTime.UtcNow.Millisecond, Name = dstDb, DbType = "postgresql",
    Host = host, Port = port, DatabaseName = dstDb, Username = user, Password = pwd
};

static async Task<string> Scalar(NpgsqlConnection conn, string sql)
{
    await using var c = conn.CreateCommand();
    c.CommandText = sql;
    var v = await c.ExecuteScalarAsync();
    return v == null || v == DBNull.Value ? "<null>" : Convert.ToString(v, System.Globalization.CultureInfo.InvariantCulture)!;
}

static async Task Exec(NpgsqlConnection conn, string sql)
{
    await using var c = conn.CreateCommand();
    c.CommandText = sql;
    await c.ExecuteNonQueryAsync();
}

string backupPath = "";
string backupFileName = "";
long backupId = 0;

try
{
    // ===== 2. 构造一个"刁钻"的向量库 =====
    await using var src = new NpgsqlConnection(Cs(srcDb));
    await src.OpenAsync();

    await Exec(src, "CREATE EXTENSION IF NOT EXISTS vector");
    await Exec(src, "CREATE SCHEMA app");
    await Exec(src, "CREATE TYPE app.mood AS ENUM ('happy','sad','中文')");
    await Exec(src, @"
CREATE TABLE app.items (
  id          serial PRIMARY KEY,
  title       text NOT NULL,
  embedding   vector(3) NOT NULL,
  feeling     app.mood DEFAULT 'happy',
  payload     bytea,
  body        text,
  created_at  timestamptz NOT NULL DEFAULT now()
)");
    await Exec(src, @"INSERT INTO app.items (title, embedding, feeling, payload, body) VALUES
 ('O''Brien; 中文', '[1,2,3]', 'happy', '\x00FF10'::bytea, 'line1
line2 -- not a comment'),
 ('second', '[0.5,0.25,0.125]', 'sad', NULL, NULL),
 ('third', '[3,2,1]', '中文', '\xDEADBEEF'::bytea, 'end')");
    await Exec(src, "CREATE INDEX idx_items_embedding ON app.items USING hnsw (embedding vector_cosine_ops)");
    await Exec(src, "CREATE UNIQUE INDEX uq_items_title ON app.items (title)");
    await Exec(src, @"
CREATE TABLE app.child (
  id       int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_id  int NOT NULL REFERENCES app.items(id),
  note     text
)");
    await Exec(src, "INSERT INTO app.child (item_id, note) VALUES (1, 'child1'), (1, 'child2')");
    await Exec(src, "CREATE VIEW app.v_items AS SELECT id, title, embedding FROM app.items");
    await Exec(src, "CREATE INDEX idx_child_note ON app.child (note)");

    var srcFingerprint = await Scalar(src, @"
SELECT md5(string_agg(t::text, '|' ORDER BY t::text)) FROM app.items t");
    var srcRows = await Scalar(src, "SELECT count(*) FROM app.items");
    var srcChild = await Scalar(src, "SELECT count(*) FROM app.child");
    Console.WriteLine($"SRC rows={srcRows} child={srcChild} fp={srcFingerprint}");

    // ===== 3. 备份 =====
    var svc = new DatabaseService();
    var backupService = new BackupService(svc);
    var connSrc = SrcConn();
    var info = await backupService.CreateBackupAsync(connSrc, "e2e_vector");
    backupFileName = info.FileName;
    backupId = connSrc.Id;
    backupPath = BackupStorage.GetSqlPath(connSrc.Id, info.FileName);

    var meta = BackupStorage.ReadMetadata(connSrc.Id, info.FileName)!;
    Console.WriteLine($"BACKUP {info.FileName} size={info.FileSize} tables={meta.TableRowCounts.Count} rows={meta.TableRowCounts.Values.Sum()}");
    Console.WriteLine($"       objects={string.Join(",", meta.SchemaObjectCounts.Select(kv => kv.Key + "=" + kv.Value))}");
    foreach (var w in meta.Warnings) Console.WriteLine("       WARN " + w);

    Check(meta.Completed && meta.Sha256 == BackupStorage.ComputeSha256(backupPath), "备份原子落盘 + SHA256");
    Check(meta.Warnings.Count == 0, "对象采集无失败告警");

    string sqlText;
    using (var payload = BackupStorage.OpenPayloadRead(backupPath, info.Compressed, info.Encrypted))
    using (var reader = new StreamReader(payload, Encoding.UTF8))
        sqlText = await reader.ReadToEndAsync();

    Check(sqlText.Contains("CREATE EXTENSION IF NOT EXISTS vector"), "备份头含 CREATE EXTENSION vector");
    Check(sqlText.Contains("vector(3)"), "备份保留向量列维度 vector(3)");
    Check(sqlText.Contains("USING hnsw") || sqlText.Contains("hnsw"), "备份含 HNSW 向量索引");
    Check(sqlText.Contains("uq_items_title"), "备份含独立唯一索引");
    Check(sqlText.Contains("CREATE SCHEMA IF NOT EXISTS \"app\""), "备份含 CREATE SCHEMA");
    Check(sqlText.Contains("CREATE TYPE"), "备份含 ENUM 类型定义");
    Check(sqlText.Contains("GENERATED BY DEFAULT AS IDENTITY"), "备份保留 identity");
    Check(sqlText.Contains("CASCADE"), "DROP TABLE 带 CASCADE（外键不阻塞）");
    Check(sqlText.Contains("reference") || sqlText.Contains("FOREIGN KEY"), "备份含外键约束");

    var pExt = sqlText.IndexOf("CREATE EXTENSION", StringComparison.Ordinal);
    var pSchema = sqlText.IndexOf("CREATE SCHEMA", StringComparison.Ordinal);
    var pSeq = sqlText.IndexOf("CREATE SEQUENCE", StringComparison.Ordinal);
    var pType = sqlText.IndexOf("CREATE TYPE", StringComparison.Ordinal);
    var pTable = sqlText.IndexOf("CREATE TABLE", StringComparison.Ordinal);
    Check(pExt >= 0 && pSchema > pExt && pSeq > pSchema && pTable > pSeq,
          "恢复顺序：扩展→schema→序列→表", $"ext={pExt} schema={pSchema} seq={pSeq} type={pType} table={pTable}");

    // ===== 4. 恢复到空的临时库（模拟 RestoreEndpoint 的核心路径）=====
    var connDst = DstConn();
    Check(BackupStorage.ComputeSha256(backupPath) == meta.Sha256, "恢复前 SHA256 校验通过");

    int executed = 0, skipped = 0;
    using (var payload = BackupStorage.OpenPayloadRead(backupPath, info.Compressed, info.Encrypted))
    using (var reader = new StreamReader(payload, Encoding.UTF8))
    {
        var splitter = new SqlStatementSplitter(reader);
        (executed, skipped) = await svc.ExecuteBatchAsync(connDst, splitter.SplitAsync(), default);
    }
    Check(executed > 0, "恢复执行成功（整批事务提交）", $"执行 {executed} 条，跳过 {skipped} 条");

    // ===== 5. 逐项比对：数据 / 向量 / 二进制 / 时间 / 对象 =====
    await using var dst = new NpgsqlConnection(Cs(dstDb));
    await dst.OpenAsync();

    var dstRows = await Scalar(dst, "SELECT count(*) FROM app.items");
    var dstChild = await Scalar(dst, "SELECT count(*) FROM app.child");
    var dstFingerprint = await Scalar(dst, "SELECT md5(string_agg(t::text, '|' ORDER BY t::text)) FROM app.items t");

    Check(srcRows == dstRows, "items 行数一致（没丢数据）", $"{srcRows} vs {dstRows}");
    Check(srcChild == dstChild, "child 行数一致", $"{srcChild} vs {dstChild}");
    Check(srcFingerprint == dstFingerprint, "整表内容指纹一致（含 vector/bytea/中文/换行）",
          $"{srcFingerprint} vs {dstFingerprint}");

    // 向量逐值比对：余弦距离为 0 才说明向量完全相同
    var vectorDiff = await Scalar(dst, @"
SELECT count(*) FROM (
  SELECT embedding::text FROM app.items ORDER BY 1
) x");
    var srcVec = await Scalar(src, "SELECT md5(string_agg(embedding::text, '|' ORDER BY embedding::text)) FROM app.items");
    var dstVec = await Scalar(dst, "SELECT md5(string_agg(embedding::text, '|' ORDER BY embedding::text)) FROM app.items");
    Check(srcVec == dstVec, "向量取值逐行一致", $"{srcVec} vs {dstVec}");

    var srcBin = await Scalar(src, "SELECT md5(string_agg(coalesce(payload::text,'-'), '|' ORDER BY id)) FROM app.items");
    var dstBin = await Scalar(dst, "SELECT md5(string_agg(coalesce(payload::text,'-'), '|' ORDER BY id)) FROM app.items");
    Check(srcBin == dstBin, "bytea 二进制一致", $"{srcBin} vs {dstBin}");

    // 对象是否全部重建
    Check(await Scalar(dst, "SELECT count(*) FROM pg_indexes WHERE indexname='idx_items_embedding' AND indexdef ILIKE '%hnsw%'") == "1",
          "HNSW 向量索引重建成功");
    Check(await Scalar(dst, "SELECT count(*) FROM pg_indexes WHERE indexname='uq_items_title'") == "1",
          "独立唯一索引重建成功");
    Check(await Scalar(dst, "SELECT count(*) FROM pg_constraint WHERE contype='f' AND conrelid='app.child'::regclass") == "1",
          "外键约束重建成功");
    Check(await Scalar(dst, "SELECT count(*) FROM pg_views WHERE schemaname='app' AND viewname='v_items'") == "1",
          "视图重建成功");
    Check(await Scalar(dst, "SELECT count(*) FROM pg_type t JOIN pg_namespace n ON n.oid=t.typnamespace WHERE t.typname='mood' AND n.nspname='app'") == "1",
          "ENUM 类型重建成功");

    // 数据可继续写入：serial / identity 序列必须已前进
    await Exec(dst, "INSERT INTO app.items (title, embedding) VALUES ('after_restore', '[9,9,9]')");
    await Exec(dst, "INSERT INTO app.child (item_id, note) VALUES (1, 'after_restore')");
    Check(await Scalar(dst, "SELECT count(*) FROM app.items") == "4", "恢复后 serial 可继续插入（序列已接续）");
    Check(await Scalar(dst, "SELECT count(*) FROM app.child") == "3", "恢复后 identity 可继续插入");

    // 向量检索仍然可用（HNSW 索引能被规划器使用）
    var knn = await Scalar(dst, "SELECT title FROM app.items ORDER BY embedding <=> '[1,2,3]' LIMIT 1");
    Check(!string.IsNullOrEmpty(knn) && knn != "<null>", "恢复后向量相似度检索可用", knn);

    // ===== 6. 恢复幂等：再恢复一次不应失败（DROP CASCADE / IF EXISTS 生效）=====
    using (var payload2 = BackupStorage.OpenPayloadRead(backupPath, info.Compressed, info.Encrypted))
    using (var reader2 = new StreamReader(payload2, Encoding.UTF8))
    {
        var splitter2 = new SqlStatementSplitter(reader2);
        await svc.ExecuteBatchAsync(connDst, splitter2.SplitAsync(), default);
    }
    Check(await Scalar(dst, "SELECT count(*) FROM app.items") == "3", "重复恢复幂等（行数回到备份值）");
    Check(await Scalar(dst, "SELECT count(*) FROM pg_indexes WHERE indexname='idx_items_embedding'") == "1",
          "重复恢复后向量索引仍存在");
}
catch (Exception ex)
{
    Console.WriteLine("FATAL: " + ex);
    failures++;
}
finally
{
    // ===== 7. 清理临时数据库（唯一删除对象，绝不碰 aichat）=====
    try
    {
        await using var admin = new NpgsqlConnection(Cs("postgres"));
        await admin.OpenAsync();
        foreach (var db in new[] { srcDb, dstDb })
        {
            await using var c = admin.CreateCommand();
            c.CommandText = $@"
SELECT pg_terminate_backend(pid) FROM pg_stat_activity WHERE datname = '{db}' AND pid <> pg_backend_pid()";
            await c.ExecuteNonQueryAsync();

            await using var d = admin.CreateCommand();
            d.CommandText = $"DROP DATABASE IF EXISTS \"{db}\" WITH (FORCE)";
            await d.ExecuteNonQueryAsync();
        }
        Console.WriteLine("CLEANUP 临时数据库已删除");
    }
    catch (Exception ex)
    {
        Console.WriteLine("CLEANUP_FAILED（请手动删除临时库）: " + ex.Message);
        Console.WriteLine($"  {srcDb} / {dstDb}");
    }
}

Console.WriteLine(failures == 0 ? "===== 真实 PG + 向量端到端验证全部通过 =====" : $"===== 有 {failures} 项失败 =====");
return failures == 0 ? 0 : 1;
